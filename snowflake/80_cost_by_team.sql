-- Credits per team (last 30 days): compute pools + warehouses, using the TEAM tag.
-- ACCOUNT_USAGE has some latency (up to a few hours).
SELECT t.TAG_VALUE AS TEAM, 'COMPUTE POOL' AS KIND, SUM(h.CREDITS_USED) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWPARK_CONTAINER_SERVICES_HISTORY h
JOIN SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES t
  ON t.DOMAIN = 'COMPUTE POOL' AND t.OBJECT_NAME = h.COMPUTE_POOL_NAME AND t.TAG_NAME = 'TEAM'
WHERE h.START_TIME >= DATEADD(day, -30, CURRENT_TIMESTAMP())
GROUP BY 1
UNION ALL
SELECT t.TAG_VALUE, 'WAREHOUSE', SUM(m.CREDITS_USED)
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY m
JOIN SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES t
  ON t.DOMAIN = 'WAREHOUSE' AND t.OBJECT_NAME = m.WAREHOUSE_NAME AND t.TAG_NAME = 'TEAM'
WHERE m.START_TIME >= DATEADD(day, -30, CURRENT_TIMESTAMP())
GROUP BY 1
ORDER BY 1, 2;
