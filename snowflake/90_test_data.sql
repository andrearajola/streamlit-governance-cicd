-- =====================================================================
-- TEST ONLY - sample data to prove owner's vs restricted caller's rights (ACCOUNTADMIN)
-- FINANCE (caller's rights): SALES has a row access policy by country, evaluated for the VIEWER.
-- COMERCIAL (owner's rights): ORDERS, read by the owner role.
-- Run: snow sql -c <conn> --enable-templating STANDARD -f 90_test_data.sql -D test_user=<YOUR_USER>
-- =====================================================================
USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS TEST_DATA_FINANCE;
CREATE SCHEMA IF NOT EXISTS TEST_DATA_FINANCE.GOLD;
CREATE OR REPLACE TABLE TEST_DATA_FINANCE.GOLD.COUNTRY_ACCESS (ROLE_NAME STRING, COUNTRY STRING);
INSERT INTO TEST_DATA_FINANCE.GOLD.COUNTRY_ACCESS VALUES
  ('FINANCE_ES_ANALYST', 'ES'), ('FINANCE_PT_ANALYST', 'PT'), ('ACCOUNTADMIN', 'ES');

CREATE TABLE IF NOT EXISTS TEST_DATA_FINANCE.GOLD.SALES (COUNTRY STRING, MONTH DATE, AMOUNT NUMBER(12,2));
-- Detach first so the policy can be replaced on a re-run
ALTER TABLE TEST_DATA_FINANCE.GOLD.SALES DROP ALL ROW ACCESS POLICIES;

CREATE OR REPLACE ROW ACCESS POLICY TEST_DATA_FINANCE.GOLD.RAP_COUNTRY AS (P_COUNTRY STRING)
RETURNS BOOLEAN ->
  EXISTS (SELECT 1 FROM TEST_DATA_FINANCE.GOLD.COUNTRY_ACCESS a
          WHERE a.COUNTRY = P_COUNTRY AND IS_ROLE_IN_SESSION(a.ROLE_NAME));

TRUNCATE TABLE TEST_DATA_FINANCE.GOLD.SALES;
INSERT INTO TEST_DATA_FINANCE.GOLD.SALES VALUES
  ('ES','2026-09-01',1200),('ES','2026-10-01',1350),('PT','2026-09-01',400),
  ('PT','2026-10-01',450),('FR','2026-09-01',900),('FR','2026-10-01',980);
ALTER TABLE TEST_DATA_FINANCE.GOLD.SALES ADD ROW ACCESS POLICY TEST_DATA_FINANCE.GOLD.RAP_COUNTRY ON (COUNTRY);

-- Functional roles of the viewers: their OWN data access (caller's rights needs it)
CREATE ROLE IF NOT EXISTS FINANCE_ES_ANALYST;
CREATE ROLE IF NOT EXISTS FINANCE_PT_ANALYST;
GRANT USAGE ON DATABASE TEST_DATA_FINANCE TO ROLE FINANCE_ES_ANALYST;
GRANT USAGE ON SCHEMA TEST_DATA_FINANCE.GOLD TO ROLE FINANCE_ES_ANALYST;
GRANT SELECT ON TABLE TEST_DATA_FINANCE.GOLD.SALES TO ROLE FINANCE_ES_ANALYST;
GRANT USAGE ON DATABASE TEST_DATA_FINANCE TO ROLE FINANCE_PT_ANALYST;
GRANT USAGE ON SCHEMA TEST_DATA_FINANCE.GOLD TO ROLE FINANCE_PT_ANALYST;
GRANT SELECT ON TABLE TEST_DATA_FINANCE.GOLD.SALES TO ROLE FINANCE_PT_ANALYST;
GRANT USAGE ON WAREHOUSE FINANCE_WH TO ROLE FINANCE_ES_ANALYST;
GRANT USAGE ON WAREHOUSE FINANCE_WH TO ROLE FINANCE_PT_ANALYST;
-- Analysts can open the FINANCE apps in both environments
GRANT ROLE FINANCE_STREAMLIT_USERS_DEV TO ROLE FINANCE_ES_ANALYST;
GRANT ROLE FINANCE_STREAMLIT_USERS     TO ROLE FINANCE_ES_ANALYST;
GRANT ROLE FINANCE_STREAMLIT_USERS_DEV TO ROLE FINANCE_PT_ANALYST;
GRANT ROLE FINANCE_STREAMLIT_USERS     TO ROLE FINANCE_PT_ANALYST;
GRANT ROLE FINANCE_ES_ANALYST TO USER <% test_user %>;
GRANT ROLE FINANCE_PT_ANALYST TO USER <% test_user %>;

CREATE DATABASE IF NOT EXISTS TEST_DATA_COMERCIAL;
CREATE SCHEMA IF NOT EXISTS TEST_DATA_COMERCIAL.GOLD;
CREATE OR REPLACE TABLE TEST_DATA_COMERCIAL.GOLD.ORDERS (REGION STRING, CHANNEL STRING, ORDERS NUMBER, REVENUE NUMBER(12,2));
INSERT INTO TEST_DATA_COMERCIAL.GOLD.ORDERS VALUES
  ('NORTE','WEB',120,15400),('NORTE','TIENDA',80,9100),('SUR','WEB',95,11200),('SUR','TIENDA',140,16800);
-- Re-run the owner's-rights grants for tables created after onboarding (future grants cover new ones)
GRANT SELECT ON ALL TABLES IN SCHEMA TEST_DATA_COMERCIAL.GOLD TO ROLE COMERCIAL_STREAMLIT_OWNER_DEV;
GRANT SELECT ON ALL TABLES IN SCHEMA TEST_DATA_COMERCIAL.GOLD TO ROLE COMERCIAL_STREAMLIT_OWNER;
GRANT ROLE COMERCIAL_STREAMLIT_USERS_DEV TO USER <% test_user %>;
GRANT ROLE COMERCIAL_STREAMLIT_USERS     TO USER <% test_user %>;
